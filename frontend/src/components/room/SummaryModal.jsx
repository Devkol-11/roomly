import { Modal } from '../ui.jsx'

const TONE = {
  positive: '!bg-live-soft !text-live',
  negative: '!bg-danger-soft !text-danger',
  tense: '!bg-danger-soft !text-danger',
  mixed: '!bg-warn-soft !text-warn',
}

export default function SummaryModal({ summary, onClose }) {
  return (
    <Modal title="Room recap" description="Generated by AI from this room’s messages." onClose={onClose} width="max-w-lg">
      <div className="flex flex-wrap gap-2">
        {summary.sentiment && <span className={`chip capitalize ${TONE[summary.sentiment] || ''}`}>{summary.sentiment}</span>}
        <span className="chip">{summary.message_count} messages</span>
      </div>
      <p className="mt-4 text-[15px] leading-7">{summary.tldr}</p>
      <Section title="Decisions" items={summary.decisions} />
      <Section title="Action items" items={summary.action_items} checkbox />
      <div className="mt-6 flex justify-end">
        <button className="btn btn-primary" onClick={onClose}>Done</button>
      </div>
    </Modal>
  )
}

function Section({ title, items, checkbox }) {
  if (!items?.length) return null
  return (
    <div className="mt-5">
      <h3 className="mb-2 text-xs font-medium uppercase tracking-wide text-fg-3">{title}</h3>
      <ul className="space-y-1.5">
        {items.map((it, i) => (
          <li key={i} className="flex gap-2.5 text-sm leading-6">
            <span className={`mt-[7px] h-2 w-2 shrink-0 ${checkbox ? 'rounded-[3px] border border-fg-3' : 'rounded-full bg-fg-3'}`} />
            {it}
          </li>
        ))}
      </ul>
    </div>
  )
}
